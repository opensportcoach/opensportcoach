// TypeScript types for the coach's results, generated from app/contracts/ — one source for both languages.
import { compileFromFile } from 'json-schema-to-typescript';
import { readdirSync, writeFileSync } from 'node:fs';
const dir = '../contracts';
let out = '/* Generated by gen-types.mjs from app/contracts/*.schema.json — do not edit. */\n';
for (const f of readdirSync(dir).filter((f) => f.endsWith('.schema.json')).sort()) {
  out += await compileFromFile(`${dir}/${f}`, { bannerComment: '', additionalProperties: false });
}
writeFileSync('src/contracts.ts', out);
console.log('wrote src/contracts.ts');
