#!/usr/bin/env python3
"""Generate every memory INDEX.md from the frontmatter of the memory files.

The index is what an agent loads FIRST: one line per fact, enough to decide which files
are worth opening. It is generated so it cannot drift from the files — the failure mode
that made CLAUDE.md unreliable in the first place.

Two kinds of memory since 2026-09-24 (multi-athlete):
  memory/                     ENGINE facts — incidents and conventions true for every athlete
  athletes/<name>/memory/     that athlete's facts — medical, goals, equipment, preferences
Deterministic and athlete-agnostic, so it rebuilds all of them in one run.

Usage: .venv/bin/python scripts/build_memory_index.py
"""
from __future__ import annotations

import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import athlete  # noqa: E402

ENGINE_MEM = athlete.REPO_ROOT / "memory"
ORDER = ["medical", "athlete", "equipment", "convention", "preference", "incident"]


def frontmatter(path: pathlib.Path) -> dict:
    text = path.read_text()
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}
    fm, key = {}, None
    for line in m.group(1).splitlines():
        if line.startswith("  - "):
            fm.setdefault(key, []).append(line[4:].strip())
        elif ":" in line:
            key, _, val = line.partition(":")
            key, val = key.strip(), val.strip()
            fm[key] = val if val else []
    return fm


def title(path: pathlib.Path) -> str:
    for line in path.read_text().splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return path.stem.replace("-", " ")


def build(mem: pathlib.Path, heading: str, intro: list[str]) -> tuple[int, int, list]:
    """Write mem/INDEX.md. Returns (facts, types, active medical facts with no enforced_by)."""
    files = sorted(p for p in mem.rglob("*.md") if p.name != "INDEX.md")
    by_type: dict[str, list] = {}
    for p in files:
        fm = frontmatter(p)
        by_type.setdefault(fm.get("type", "untyped"), []).append((p, fm))

    out = [heading,
           "",
           "GENERATED by `scripts/build_memory_index.py` — do not hand-edit.",
           "",
           *intro,
           "One fact per file. Load this first, then open only what you need. **`enforced_by` is the",
           "field that matters**: it names the assertion that makes a fact non-optional. A fact with no",
           "`enforced_by` is a fact an agent can violate.",
           ""]
    for t in ORDER + [k for k in sorted(by_type) if k not in ORDER]:
        entries = by_type.get(t)
        if not entries:
            continue
        out.append(f"## {t}")
        out.append("")
        for p, fm in sorted(entries, key=lambda x: x[0].name):
            rel = p.relative_to(mem)
            status = fm.get("status", "?")
            enf = fm.get("enforced_by", "")
            mark = "" if (enf and enf != "none" and not str(enf).startswith("none")) else " ⚠ unenforced"
            flag = "" if status == "active" else f" · _{status}_"
            out.append(f"- [{title(p)}]({rel}) — since {fm.get('since','?')}{flag}{mark}")
        out.append("")
    (mem / "INDEX.md").write_text("\n".join(out).rstrip() + "\n")

    unenforced = [p.name for p, fm in
                  [(p, frontmatter(p)) for p in files]
                  if fm.get("type") == "medical"
                  and (not fm.get("enforced_by") or str(fm["enforced_by"]).startswith("none"))
                  and fm.get("status") == "active"]
    return len(files), len(by_type), unenforced


def roots() -> list[tuple[pathlib.Path, str, list[str]]]:
    """(memory dir, heading, intro lines) for the engine and every athlete."""
    out = [(ENGINE_MEM, "# Memory index — engine",
            ["Facts true for EVERY athlete: incidents, audit and progression conventions, the Garmin",
             "write discipline. Each athlete's own facts live in `athletes/<name>/memory/INDEX.md`.",
             ""])]
    for name in athlete.known():
        mem = athlete.ATHLETES_DIR / name / "memory"
        if mem.is_dir():
            display = athlete.load(name).display
            out.append((mem, f"# Memory index — {display}",
                        [f"Facts about {display}. Engine facts that apply to every athlete are in",
                         "`memory/INDEX.md` at the repo root.",
                         ""]))
    return out


def main() -> None:
    bad = []
    for mem, heading, intro in roots():
        n, types, unenforced = build(mem, heading, intro)
        print(f"{mem.relative_to(athlete.REPO_ROOT) if mem.is_relative_to(athlete.REPO_ROOT) else mem}"
              f"/INDEX.md: {n} facts across {types} types")
        bad += unenforced
    if bad:
        print(f"  WARNING: active medical facts with no enforced_by: {bad}")
        sys.exit(1)


if __name__ == "__main__":
    main()
